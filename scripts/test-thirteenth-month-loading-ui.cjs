// Mount the real annual page against delayed synthetic responses, never live data.
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const {build}=require('./test-thirteenth-month-ui.cjs'),{annualSummary}=require('../shared/utils/thirteenthMonth.ts')
test('annual page appends rows on scroll, exports all records, deduplicates loads and ignores responses after leaving',async()=>{
 const {chromium}=require('playwright'),fixture=await build('app/pages/payroll/thirteenth-month/index.vue'),browser=await chromium.launch({executablePath:process.env.CHROME_BIN||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:980}}),errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.setContent('<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><div id="app"></div>');await page.addStyleTag({content:fixture.css})
  const source={id:'payroll:1',start:'2026-01-01',end:'2026-01-31',reference:'Synthetic payroll',site:'Synthetic site',kind:'Finalized payroll',basic:12000,timeDeductions:0,adjustments:0,excluded:0,issues:[]}
  const summary=annualSummary([source],'2026-01-01','2026-01-31')
  const items=Array.from({length:200},(_,i)=>({EmployeeID:i+1,EmployeeName:'Synthetic employee '+(i+1),EmployeeNumber:'SYN-'+(i+1),AgencyID:1,AgencyName:'Synthetic agency',sources:[source],summary,releases:[],imports:[],adjustmentReviews:[],events:[],coverageStart:'2026-01-01',coverageEnd:'2026-01-31',sourceHash:'synthetic-source-'+i,sourceChanged:false,header:{ThirteenthMonthID:i+1,Revision:1,Status:i<60?'Approved':'Draft',ThirteenthMonthAmount:1000}}))
  await page.evaluate(initial=>{
   window.annualFixture=initial;window.calls=[];window.delayed=[];window.slow=false;window.syntheticNow=Date.now();Date.now=()=>window.syntheticNow
   window.$fetch=(url,options={})=>new Promise(resolve=>{
    const call={url,query:options.query,aborted:false,retry:options.retry,timeout:options.timeout};window.calls.push(call)
    // Deliberately let an aborted response resolve later: the UI must reject it itself.
    options.signal?.addEventListener('abort',()=>{call.aborted=true})
    const finish=label=>{const result=structuredClone(window.annualFixture);if(label)result.items[0].EmployeeName=label;resolve(result)}
    if(window.slow)window.delayed.push({finish});else finish()
   })
  },{year:2026,items,agencies:[{AgencyID:1,AgencyName:'Synthetic agency'}],permissions:{canEdit:true,canApprove:true}})
  await page.addScriptTag({content:fixture.script});await page.getByText('Showing 25 of 200 records',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Next',exact:true}).count(),0);assert.equal(await page.getByRole('button',{name:'Previous',exact:true}).count(),0)
  assert.equal(await page.locator('.table-wrap tbody tr').count(),25);assert.equal(await page.locator('.mobile-cards article').count(),25)
  const totals=await page.locator('.summary').first().innerText();assert.match(totals,/2,400,000/)
  const initialReads=await page.evaluate(()=>window.calls.length)
  await page.getByRole('button',{name:'Load more records',exact:true}).scrollIntoViewIfNeeded()
  await page.getByText('Showing 50 of 200 records',{exact:true}).waitFor()
  assert.match(await page.locator('.table-wrap tbody tr').first().innerText(),/Synthetic employee 1\b/)
  assert.match(await page.locator('.table-wrap tbody tr').last().innerText(),/Synthetic employee 50\b/)
  assert.equal(await page.locator('.summary').first().innerText(),totals)
  assert.equal(await page.evaluate(()=>window.calls.length),initialReads,'Scrolling appends existing report rows without another annual calculation request')
  const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Export Excel',exact:true}).click();const download=await downloaded
  const target=path.resolve('.data/thirteenth-month-ui/scroll-export.xlsx');fs.mkdirSync(path.dirname(target),{recursive:true});await download.saveAs(target)
  const x=require('xlsx');assert.equal(x.utils.sheet_to_json(x.readFile(target).Sheets['Annual summary']).length,200)
  // Reach the end without page navigation or dropping previously rendered rows.
  for(let count=75;count<=200;count+=25){
   await page.getByRole('button',{name:'Load more records',exact:true}).scrollIntoViewIfNeeded()
   await page.getByText(`Showing ${count} of 200 records`,{exact:true}).waitFor()
  }
  assert.equal(await page.locator('.table-wrap tbody tr').count(),200)
  assert.equal(await page.getByRole('button',{name:'Load more records',exact:true}).count(),0)
  assert.equal(await page.evaluate(()=>window.calls.length),initialReads)
  await page.getByRole('button',{name:'Release History',exact:true}).click()
  await page.getByText('Showing 25 of 60 records',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Load more records',exact:true}).scrollIntoViewIfNeeded()
  await page.getByText('Showing 50 of 60 records',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Load more records',exact:true}).scrollIntoViewIfNeeded()
  await page.getByText('Showing 60 of 60 records',{exact:true}).waitFor()
  assert.equal(await page.locator('.history-cards article').count(),60)
  await page.getByRole('button',{name:'Computation',exact:true}).click()
  await page.getByText('Showing 25 of 200 records',{exact:true}).waitFor()
  await page.setViewportSize({width:375,height:812})
  await page.getByRole('button',{name:'Load more records',exact:true}).scrollIntoViewIfNeeded()
  await page.getByText('Showing 50 of 200 records',{exact:true}).waitFor()
  assert.equal(await page.locator('.mobile-cards article').count(),50)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1))
  await page.getByLabel('Search employee',{exact:true}).fill('missing synthetic employee')
  await page.locator('.empty:visible').filter({hasText:'No employees match your filters.'}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Load more records',exact:true}).count(),0)
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.getByLabel('Search employee',{exact:true}).fill('')
  await page.getByText('Showing 25 of 200 records',{exact:true}).waitFor()
  await page.setViewportSize({width:1440,height:980})
  const before=await page.evaluate(()=>window.calls.length)
  await page.evaluate(()=>{for(let n=0;n<5;n++){window.dispatchEvent(new Event('focus'));document.dispatchEvent(new Event('visibilitychange'))}})
  assert.equal(await page.evaluate(()=>window.calls.length),before,'Fresh results must not reload on every focus event')
  await page.evaluate(()=>{window.slow=true})
  await page.getByRole('button',{name:'Refresh',exact:true}).evaluate(button=>{button.click();button.click()})
  await page.waitForFunction(()=>window.delayed.length===1);assert.equal(await page.evaluate(()=>window.calls.length),before+1)
  assert.equal(await page.evaluate(()=>window.calls.at(-1).query.fresh),'1')
  await page.evaluate(()=>{window.syntheticNow+=46000;window.annualVisible.value=false})
  await page.getByText('Other workspace',{exact:true}).waitFor();assert.equal(await page.evaluate(()=>window.calls.at(-1).aborted),true)
  await page.evaluate(()=>{window.annualVisible.value=true})
  await page.waitForFunction(()=>window.delayed.length===2)
  await page.evaluate(()=>window.delayed[1].finish('Newest synthetic result'))
  await page.getByText('Newest synthetic result',{exact:true}).first().waitFor()
  await page.evaluate(()=>window.delayed[0].finish('Stale synthetic result'))
  assert.equal(await page.getByText('Stale synthetic result',{exact:true}).count(),0)
  assert.equal(await page.getByText('Newest synthetic result',{exact:true}).count(),2)
  await page.getByLabel('Search employee',{exact:true}).fill('missing synthetic employee')
  await page.locator('.empty:visible').filter({hasText:'No employees match your filters.'}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Load more records',exact:true}).count(),0)
  assert.ok((await page.evaluate(()=>window.calls)).every(call=>call.retry===0&&call.timeout===30000));assert.deepEqual(errors,[])
  const fallback=await browser.newPage({viewport:{width:1440,height:980}})
  fallback.on('pageerror',e=>errors.push(e.message))
  await fallback.setContent('<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><div id="app"></div>');await fallback.addStyleTag({content:fixture.css})
  await fallback.evaluate(initial=>{window.IntersectionObserver=undefined;window.$fetch=async()=>structuredClone(initial)},await page.evaluate(()=>window.annualFixture))
  await fallback.addScriptTag({content:fixture.script});await fallback.getByText('Showing 25 of 200 records',{exact:true}).waitFor()
  await fallback.getByRole('button',{name:'Load more records',exact:true}).focus();await fallback.keyboard.press('Enter')
  await fallback.getByText('Showing 50 of 200 records',{exact:true}).waitFor()
  assert.equal(await fallback.locator('.table-wrap tbody tr').count(),50);assert.deepEqual(errors,[])

 }finally{await browser.close()}
})
