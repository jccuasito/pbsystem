-- MariaDB additive schema; contains no seed data and preserves existing amounts.
CREATE TABLE IF NOT EXISTS payroll_region_rate (
  RegionRateID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  AgencyID INT NOT NULL,
  RegionID INT NULL,
  RegionKey INT GENERATED ALWAYS AS (COALESCE(RegionID,0)) STORED,
  EffectiveDate DATE NOT NULL,
  RegularRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  OTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  OTExtRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  NightDiffRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  RestDayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  RestDayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  SpecialHolidayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LegalHolidayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  SpecialHolidayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LegalHolidayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LateDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  UndertimeDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  BreakDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  Allowance DECIMAL(10,2) NOT NULL DEFAULT 0,
  Reason VARCHAR(500) NOT NULL DEFAULT '',
  Status ENUM('Active','Inactive') NOT NULL DEFAULT 'Active',
  Revision INT NOT NULL DEFAULT 1,
  CreatedBy INT NULL,
  UpdatedBy INT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_region_rate_scope (AgencyID,RegionKey),
  FOREIGN KEY (AgencyID) REFERENCES agency(AgencyID),
  FOREIGN KEY (RegionID) REFERENCES region(RegionID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payroll_region_rate_version (
  RegionRateVersionID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  RegionRateID INT NOT NULL,
  EffectiveDate DATE NOT NULL,
  RegularRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  OTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  OTExtRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  NightDiffRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  RestDayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  RestDayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  SpecialHolidayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LegalHolidayRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  SpecialHolidayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LegalHolidayOTRate DECIMAL(10,2) NOT NULL DEFAULT 0,
  LateDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  UndertimeDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  BreakDeduction DECIMAL(10,2) NOT NULL DEFAULT 0,
  Allowance DECIMAL(10,2) NOT NULL DEFAULT 0,
  Reason VARCHAR(500) NOT NULL DEFAULT '',
  CreatedBy INT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_region_rate_version_date (RegionRateID,EffectiveDate),
  FOREIGN KEY (RegionRateID) REFERENCES payroll_region_rate(RegionRateID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

