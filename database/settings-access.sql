CREATE TABLE IF NOT EXISTS user_module_permission (
  UserID INT NOT NULL,
  ModuleKey VARCHAR(40) NOT NULL,
  CanView TINYINT(1) NOT NULL DEFAULT 0,
  CanEdit TINYINT(1) NOT NULL DEFAULT 0,
  UpdatedBy INT NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (UserID, ModuleKey),
  CONSTRAINT fk_user_module_permission_user FOREIGN KEY (UserID) REFERENCES `user` (UserID) ON DELETE CASCADE
);
